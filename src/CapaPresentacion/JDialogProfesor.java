    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
      
        int e = JOptionPane.showConfirmDialog(null, "Desea Eliminar? "+ txtNombre.getText(),"Eliminar" , JOptionPane.YES_NO_CANCEL_OPTION);
        if (e==0 ) {
            PLG.Eliminar(txtCedula.getText());
            showTable();
            cleanWin();
            JOptionPane.showMessageDialog(null, "Dato eliminado");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblProfesorMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProfesorMouseClicked
       
        int i = tblProfesor.getSelectedRow();
        txtCedula.setText(tblProfesor.getValueAt(i, 0).toString());
        txtNombre.setText(tblProfesor.getValueAt(i, 1).toString());
        txtApellido1.setText(tblProfesor.getValueAt(i, 2).toString());
        txtApellido2.setText(tblProfesor.getValueAt(i, 3).toString());
        txtFechaM.setText(tblProfesor.getValueAt(i, 4).toString());
        txtCorreo.setText(tblProfesor.getValueAt(i, 5).toString());
        txtCarnet.setText(tblProfesor.getValueAt(i, 6).toString());
        txtExperiencia.setText(tblProfesor.getValueAt(i, 7).toString());
        txtCedula.setEnabled(false);
        btnGuardar.setEnabled(false);
        
    }//GEN-LAST:event_tblProfesorMouseClicked

